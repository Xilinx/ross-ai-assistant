"""
base.py -- the compute backend interface, and the on-disk job handle.

A backend does four things: submit, status, kill, logs. Nothing else about the
flow belongs here; `run.tcl` is generated by tcl_gen.py and classified by
`orchestrate.py run-status`.

Two rules this module exists to enforce:

1. **Files stay authoritative.** `run-status` already classifies a run from
   `run.done` / `run.failed` / `hs_err` / `hs_mangled_err` / exit 139, and that
   stays the source of truth. A backend's view is *supplementary evidence*,
   passed on as `run-status --lsf-status`. This is why a crashed run that LSF
   still calls RUN is reported failed (the Ciena workflow ended early for
   exactly the opposite reason before the crash short-circuit went in).

2. **A job outlives the process that submitted it.** The handle is written to
   `job.json` in the run directory *before* the submit is acknowledged, so an
   engine restart re-adopts running work instead of relaunching it. The defect
   this closes is ENHANCEMENTS.md section 6: "Tied to a live Claude session. If
   it exits, in-flight runs are lost."

Stdlib only; never parses a timing report. Requires Python 3.6+.
"""

from __future__ import print_function

import os

from .. import jsonio

JOB_FILE = "job.json"

# JobStatus.state values. Deliberately coarse: the fine-grained failure classes
# (oom, lsf_killed, license, crash, vivado_error, interrupted) are decided by
# orchestrate.py from the run directory, not here.
PENDING = "pending"
RUNNING = "running"
DONE = "done"
FAILED = "failed"
UNKNOWN = "unknown"

TERMINAL = (DONE, FAILED)


class SubmitError(Exception):
    """The backend could not submit. Never raised for a job that failed later."""


class LauncherUnavailable(SubmitError):
    """
    The launcher itself is down (an MCP server that will not start or answer),
    as opposed to a refusal of this particular job. A failover backend counts
    these; a refusal it passes through.
    """


class Resources(object):
    """What a run asks the scheduler for. None means "backend default"."""

    __slots__ = ("queue", "memory_mb", "slots", "os_type", "runtime_limit_min",
                 "job_name", "extra")

    def __init__(self, queue=None, memory_mb=None, slots=None, os_type=None,
                 runtime_limit_min=None, job_name=None, extra=None):
        self.queue = queue
        self.memory_mb = memory_mb
        self.slots = slots
        self.os_type = os_type
        self.runtime_limit_min = runtime_limit_min
        self.job_name = job_name
        self.extra = list(extra or [])

    def to_dict(self):
        return {k: getattr(self, k) for k in self.__slots__}

    @classmethod
    def from_dict(cls, d):
        d = dict(d or {})
        return cls(**{k: d.get(k) for k in cls.__slots__})


class JobHandle(object):
    """
    Identifies a submitted job well enough to find it again after a restart.

    `job_id` is the scheduler's id for LSF, or the pid for local.
    """

    __slots__ = ("backend", "job_id", "run_dir", "log_path", "submitted_utc",
                 "resources")

    def __init__(self, backend, job_id, run_dir, log_path=None,
                 submitted_utc=None, resources=None):
        self.backend = backend
        self.job_id = str(job_id)
        self.run_dir = run_dir
        self.log_path = log_path
        self.submitted_utc = submitted_utc
        self.resources = resources or {}

    def to_dict(self):
        return {k: getattr(self, k) for k in self.__slots__}

    @classmethod
    def from_dict(cls, d):
        return cls(**{k: d.get(k) for k in cls.__slots__})


class JobStatus(object):
    """A backend's view of a job. Supplementary to the run directory."""

    __slots__ = ("state", "host", "exit_code", "term_reason", "raw")

    def __init__(self, state, host=None, exit_code=None, term_reason=None,
                 raw=None):
        self.state = state
        self.host = host
        self.exit_code = exit_code
        self.term_reason = term_reason
        self.raw = raw

    def to_dict(self):
        return {k: getattr(self, k) for k in self.__slots__}


def save_handle(handle):
    """Written before the submit is acknowledged; see the module docstring."""
    jsonio.write(os.path.join(handle.run_dir, JOB_FILE), handle.to_dict())


def load_handle(run_dir):
    """The handle for a run dir, or None when nothing was ever submitted."""
    d = jsonio.read(os.path.join(run_dir, JOB_FILE))
    return JobHandle.from_dict(d) if d else None


def clear_handle(run_dir):
    """
    Forget the job for a run dir, making it eligible for submission again.

    Called only after `prepare-retry` has quarantined the failed attempt into
    attempt_<n>/. Without this a retried run would still carry its old
    terminal handle and never be resubmitted.
    """
    try:
        os.unlink(os.path.join(run_dir, JOB_FILE))
    except (IOError, OSError):
        pass


class ComputeBackend(object):
    """Submit, status, kill, logs. Implementations: local.py, lsf.py."""

    name = "base"

    def submit(self, run_dir, run_tcl, resources=None):
        """Start `run_tcl` in `run_dir`, detached. Returns a JobHandle."""
        raise NotImplementedError

    def status(self, handle):
        """The scheduler's view. Returns a JobStatus. Never raises for a
        job it cannot find -- that is UNKNOWN, and the files decide."""
        raise NotImplementedError

    def kill(self, handle):
        raise NotImplementedError

    def logs(self, handle):
        """Path to the backend's own log for the job, or None."""
        return handle.log_path

    # -- keep-alive -----------------------------------------------------

    # Whether a run's Vivado stays loaded after run.tcl finishes, so the
    # design can be queried without re-opening its checkpoint. False for a
    # batch backend, where `vivado -mode batch -source run.tcl` exits on its
    # own and the slot is released the moment the work is done.
    supports_keepalive = False

    def release(self, handle):
        """
        Stop holding a finished run's session.

        A no-op where runs do not survive their script: there is nothing left
        to release, and sending a kill to a job that already exited would only
        produce noise in the logs. Session-capable backends override this.
        """
        return

    # -- shared helpers -------------------------------------------------

    def adopt(self, run_dir):
        """Re-attach to a job submitted by an earlier engine process."""
        return load_handle(run_dir)

    def available(self):
        """Whether this backend can be used on this host."""
        return True
