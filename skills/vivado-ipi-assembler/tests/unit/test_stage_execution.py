class StageSafety(unittest.TestCase):
    run_tcl = StageExecution.run_tcl

    def test_empty_stage_cannot_complete(self):
        plan = plan_fixture()
        plan["stages"][1]["operations"] = []
        with self.assertRaises(compiler.PlanError):
            compiler.compile_plan(plan, stage="board")

    def test_selected_compile_excludes_bootstrap_and_later(self):
        plan = plan_fixture()
        plan["stages"][0]["operations"] = [
            {"op": "create_bd_design", "name": "delivery", "expect": ["BD:OK"]}
        ]
        compiled = compiler.compile_plan(plan, stage="cells")
        self.assertNotIn("create_bd_design", compiled)

    def test_full_bootstrap_then_selected_stage_does_not_recreate(self):
        plan = plan_fixture()
        plan["stages"][0]["operations"].insert(0, {
            "op": "create_bd_design", "id": "bootstrap", "name": "delivery", "expect": ["BD:OK"],
        })
        self.run_tcl("""
set design {}
set creates 0
proc create_bd_design {name} {incr ::creates; set ::design $name}
set result [ipiasm::assemble_from_plan $plan]
assert {[string match "ASSEMBLY_PLAN:PASS*" $result]} $result
set result [ipiasm::assemble_from_plan $plan cells]
assert {[string match "ASSEMBLY_PLAN:PARTIAL*" $result]} $result
assert {$creates == 1 && $calls eq {board cells later cells}} "bootstrap repeated"
""", plan)

    def test_bootstrap_adopts_an_open_empty_bd_of_its_name(self):
        plan = plan_fixture()
        plan["stages"][0]["operations"].insert(0, {
            "op": "create_bd_design", "id": "bootstrap", "name": "delivery", "expect": ["BD:OK"],
        })
        self.run_tcl("""
set creates 0
set cells {}
proc current_bd_design {args} {return $::design}
proc get_bd_cells {args} {return $::cells}
proc get_bd_ports {args} {return {}}
proc get_bd_intf_ports {args} {return {}}
proc create_bd_design {name} {incr ::creates; set ::design $name}
set result [ipiasm::assemble_from_plan $plan]
assert {[string match "ASSEMBLY_PLAN:PASS*" $result]} $result
assert {$creates == 0} "an open empty BD of the plan's name was created again"
ipiasm::begin_design
set cells {/leftover}
set creates 0
set result [ipiasm::assemble_from_plan $plan]
assert {$creates == 1} "a BD with cells in it was adopted"
""", plan)

    def test_whole_rerun_resumes_after_completed_stages_of_a_built_bd(self):
        self.run_tcl("""
set cells {/built}
proc get_bd_cells {args} {return $::cells}
set fail_stage later
set result [ipiasm::assemble_from_plan $plan]
assert {[string match "ASSEMBLY_PLAN_FAIL:*" $result]} $result
set fail_stage {}
set calls {}
set result [ipiasm::assemble_from_plan $plan]
assert {[string match "ASSEMBLY_PLAN:PASS*resumed_after={board cells}*" $result]} $result
assert {$calls eq {later}} "completed stages ran again: $calls"
set fail_stage later
ipiasm::assemble_from_plan $plan
set fail_stage {}
set cells {}
set calls {}
set result [ipiasm::assemble_from_plan $plan]
assert {[string match "ASSEMBLY_PLAN:PASS*" $result] && $calls eq {board cells later}} "an emptied BD resumed: $calls $result"
""")

