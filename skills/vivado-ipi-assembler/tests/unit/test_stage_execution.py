def plan_fixture():
    return {
        "schema_version": 1,
        "stages": [
            {"name": name, "operations": [
                {"id": name + "_check", "op": "call", "proc": "ipiasm::stage",
                 "args": [name], "expect": ["SUCCESS:"]}
            ]} for name in ("board", "cells", "later")
        ],
    }


class StageExecution(unittest.TestCase):
    def run_tcl(self, body, plan=None):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            plan_path = root / "plan.json"
            plan_path.write_text(json.dumps(plan or plan_fixture()))
            # A plan runs only beside its DesignSpec (the plan gate refuses one without).
            (root / "design_spec.json").write_text(json.dumps({"blocks": []}))
            (root / "spec_sources.json").write_text(json.dumps([{"id": "reference-search",
                "text": "fixture: no matching reference design", "sha256": "0"}]))
            (root / "reference_search.json").write_text(json.dumps({"schema": "reference_search/1", "ranking": []}))
            script = root / "test.tcl"
            script.write_text(f"""
source {{{SKILL / 'lib/ipiasm.tcl'}}}
rename source tcl_source
proc source {{args}} {{
    if {{[lindex $args 0] eq "-notrace"}} {{set args [lrange $args 1 end]}}
    uplevel 1 [list tcl_source {{*}}$args]
}}
set plan {{{plan_path}}}
set project_dir {{{root}}}
set design delivery
set calls {{}}
set fail_stage {{}}
set response {{SUCCESS:verified with spaces}}
set native_console {{}}
proc get_msg_config {{args}} {{
    return [regexp -all -line "^[lindex $args 1]:" $::native_console]
}}
proc write_messages {{args}} {{
    set channel [open [lindex $args end] w]
    puts $channel "\n########\n# Generated by Vivado fixture\n# Command Used: write_messages\n########\n"
    puts -nonewline $channel $::native_console
    close $channel
}}
proc current_project {{}} {{return project}}
proc current_bd_design {{}} {{return $::design}}
proc version {{args}} {{return 2026.1}}
proc get_property {{args}} {{
    switch -- [lindex $args end-1] {{
        DIRECTORY {{return $::project_dir}}
        PART {{return part}}
        BOARD_PART {{return board}}
    }}
    return {{}}
}}
proc create_bd_design {{name}} {{error UNAUTHORIZED_CREATE}}
proc get_files {{args}} {{return {{}}}}
proc ipiasm::stage {{name}} {{
    lappend ::calls $name
    if {{$name eq $::fail_stage}} {{error "fixture diagnostic: $name"}}
    return $::response
}}
proc assert {{expression message}} {{
    if {{![uplevel 1 [list expr $expression]]}} {{error $message}}
}}
if {{[catch {{
{body}
}} message options]}} {{
    puts stderr [dict get $options -errorinfo]
    exit 1
}}
""")
            result = subprocess.run(["tclsh", str(script)], capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
            return result.stdout

